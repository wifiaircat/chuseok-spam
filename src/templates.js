export const pick = (arr) => arr[Math.floor(Math.random() * arr.length)]

export function localMessage(styleId) {
  const g = pick(PARTS[styleId] ?? PARTS.delivery)
  const head = pick(HEAD_FORMATS)(pick(g.heads))
  const body = pick(g.bodies) + pick(BODY_TAILS)
  const link = pick(LINK_FORMATS)(pick(g.ctas))
  const extra = Math.random() < 0.4 ? `\n${pick(EXTRAS)}` : ''
  return `${head} ${body}\n${link}${extra}`
}
